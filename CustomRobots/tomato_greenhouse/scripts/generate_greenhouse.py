def periodic_noise(size, scales, seed):
    r = np.random.default_rng(seed)
    out = np.zeros((size, size))
    fy = np.fft.fftfreq(size)[:, None]
    fx = np.fft.fftfreq(size)[None, :]
    f = np.sqrt(fx ** 2 + fy ** 2)
    for scale, amp in scales:
        spec = np.fft.fft2(r.normal(size=(size, size)))
        filt = np.exp(-(f * scale) ** 2)
        n = np.real(np.fft.ifft2(spec * filt))
        n = (n - n.mean()) / (n.std() + 1e-9)
        out += amp * n
    return out


def peat_texture(path, size=1024):
    n = periodic_noise(size, [(60, 0.5), (20, 0.35), (5, 0.25), (1.5, 0.2)], 1)
    base = np.array([0.25, 0.165, 0.10])
    img = np.clip(base[None, None, :] * (1.0 + 0.22 * n[..., None]), 0, 1)
    pil = Image.fromarray((img * 255).astype(np.uint8))
    d = ImageDraw.Draw(pil)
    r = np.random.default_rng(2)
    # Fibres
    for _ in range(2600):
        x, y = r.uniform(0, size, 2)
        a = r.uniform(0, math.pi)
        ln = r.uniform(4, 16)
        col = tuple(int(v) for v in r.uniform([70, 45, 25], [120, 85, 50]))
        for dx in (-size, 0, size):
            for dy in (-size, 0, size):
                d.line([(x + dx, y + dy), (x + dx + ln * math.cos(a), y + dy + ln * math.sin(a))], fill=col, width=1)
    # Perlite grains
    for _ in range(220):
        x, y = r.uniform(0, size, 2)
        rad = r.uniform(0.7, 1.6)
        g = int(r.uniform(200, 240))
        for dx in (-size, 0, size):
            for dy in (-size, 0, size):
                d.ellipse([x + dx - rad, y + dy - rad, x + dx + rad, y + dy + rad], fill=(g, g, g - 8))
    pil = pil.filter(ImageFilter.GaussianBlur(0.6))
    pil.save(path)


def grass_texture(path, size=512):
    n = periodic_noise(size, [(40, 0.5), (8, 0.4), (1.5, 0.35)], 3)
    base = np.array([0.30, 0.42, 0.17])
    img = np.clip(base[None, None, :] * (1.0 + 0.2 * n[..., None]), 0, 1)
    Image.fromarray((img * 255).astype(np.uint8)).save(path)


def wood_texture(path, size=512):
    r = np.random.default_rng(4)
    y = np.arange(size)[:, None]
    warp = periodic_noise(size, [(30, 1.0)], 5) * 6
    grain = np.sin((y + warp) * 2 * math.pi * 14 / size) * 0.5 + 0.5
    fine = periodic_noise(size, [(1.2, 1.0)], 6)
    streak = periodic_noise(size, [(4, 1.0)], 7)
    v = 0.82 + 0.10 * grain + 0.03 * fine + 0.04 * streak
    base = np.array([0.80, 0.62, 0.40])
    img = np.clip(base[None, None, :] * v[..., None], 0, 1)
    # Knots
    pil = Image.fromarray((img * 255).astype(np.uint8))
    d = ImageDraw.Draw(pil)
    for _ in range(3):
        cx, cy = r.uniform(40, size - 40, 2)
        d.ellipse([cx - 9, cy - 5, cx + 9, cy + 5], fill=(120, 80, 45))
    pil.filter(ImageFilter.GaussianBlur(0.7)).save(path)


def flat_quad_mesh(path, x0, x1, y0, y1, z, tile):
    m = Mesh()
    v = [(x0, y0, z), (x1, y0, z), (x1, y1, z), (x0, y1, z)]
    uv = [(x0 / tile, y0 / tile), (x1 / tile, y0 / tile), (x1 / tile, y1 / tile), (x0 / tile, y1 / tile)]
    m.add(v, [(0, 0, 1)] * 4, uv, [(0, 1, 2), (0, 2, 3)])
    m.write(path)


