def tex_material(uri, diffuse="1 1 1 1"):
    return f"""<material>
            <ambient>{diffuse}</ambient>
            <diffuse>{diffuse}</diffuse>
            <specular>0.05 0.05 0.05 1</specular>
            <pbr><metal><albedo_map>{uri}</albedo_map><metalness>0</metalness><roughness>0.9</roughness></metal></pbr>
          </material>"""


def build_rows():
    d = mkmodel("greenhouse_tomato_rows")
    write_palette(os.path.join(d, "materials", "textures", "palette.png"))
    pal = "model://greenhouse_tomato_rows/materials/textures/palette.png"
    variants = []
    for i in range(N_VARIANTS):
        mesh, trusses = plant_variant(SEED + 17 * i)
        mesh.write(os.path.join(d, "meshes", f"tomato_plant_{i}.obj"))
        variants.append(trusses)
        print(f"plant {i}: {len(mesh.v)} verts {len(mesh.f)} tris")
    line_mesh().write(os.path.join(d, "meshes", "plant_line.obj"))
    row_extras_mesh().write(os.path.join(d, "meshes", "row_extras.obj"))
    sign_mesh(os.path.join(d, "meshes", "sign.obj"))
    for k in range(len(ROW_CENTERS)):
        sign_texture(os.path.join(d, "materials", "textures", f"row_{k + 1}.png"), k + 1)

    r = np.random.default_rng(SEED + 1)
    links = []
    anchors_out = []
    line_id = 0
    for row_idx, yc in enumerate(ROW_CENTERS):
        for side in (-1, 1):
            y_line = yc + side * LINE_OFFSET
            # Plants face the aisle on the outer side of the double row
            face_yaw = side * math.pi / 2
            stagger = 0.0 if side < 0 else PLANT_STEP / 2
            xs = np.arange(-ROW_HALF_LEN + 0.25 + stagger, ROW_HALF_LEN - 0.2, PLANT_STEP)
            visuals = [f"""
        <visual name="line">
          <geometry><mesh><uri>model://greenhouse_tomato_rows/meshes/plant_line.obj</uri></mesh></geometry>
          {tex_material(pal)}
        </visual>"""]
            for j, x in enumerate(xs):
                v = int(r.integers(N_VARIANTS))
                # Small jitter so the trusses of neighbouring plants never cross
                yaw = face_yaw + r.normal(0, 0.08)
                visuals.append(f"""
        <visual name="plant_{j}">
          <pose>{x:.3f} 0 {SLAB_TOP} 0 0 {yaw:.3f}</pose>
          <geometry><mesh><uri>model://greenhouse_tomato_rows/meshes/tomato_plant_{v}.obj</uri></mesh></geometry>
          {tex_material(pal)}
        </visual>""")
                c, s = math.cos(yaw), math.sin(yaw)
                def world(pt):
                    ax, ay, az = pt
                    return [round(x + c * ax - s * ay, 4), round(y_line + s * ax + c * ay, 4), round(SLAB_TOP + az, 4)]
                for t in variants[v]:
                    anchors_out.append({
                        "line": line_id, "row": row_idx + 1, "plant": j, "level": t["level"],
                        "anchors": [world(p) for p in t["anchors"]],
                        "stalk": [world(p) for p in t["stalk"]],
                        "pedicels": [[world(a), world(b)] for a, b in t["pedicels"]]})
            links.append(f"""
      <link name="line_{line_id}">
        <pose>0 {y_line:.3f} 0 0 0 0</pose>
        <collision name="gutter">
          <pose>0 0 {SLAB_TOP / 2:.3f} 0 0 0</pose>
          <geometry><box><size>{2 * ROW_HALF_LEN:.2f} 0.26 {SLAB_TOP:.2f}</size></box></geometry>
        </collision>
        <collision name="post_east">
          <pose>{ROW_HALF_LEN + 0.12:.2f} 0 {WIRE_Z / 2:.2f} 0 0 0</pose>
          <geometry><box><size>0.05 0.05 {WIRE_Z:.2f}</size></box></geometry>
        </collision>
        <collision name="post_west">
          <pose>{-ROW_HALF_LEN - 0.12:.2f} 0 {WIRE_Z / 2:.2f} 0 0 0</pose>
          <geometry><box><size>0.05 0.05 {WIRE_Z:.2f}</size></box></geometry>
        </collision>{''.join(visuals)}
      </link>""")
            line_id += 1
        sign_vis = ""
        for end, xs_, yaw in (("east", ROW_HALF_LEN + 0.145, 0.0), ("west", -ROW_HALF_LEN - 0.145, math.pi)):
            sign_vis += f"""
        <visual name="sign_{end}">
          <pose>{xs_:.3f} 0 1.35 0 0 {yaw:.4f}</pose>
          <geometry><mesh><uri>model://greenhouse_tomato_rows/meshes/sign.obj</uri></mesh></geometry>
          {tex_material(f"model://greenhouse_tomato_rows/materials/textures/row_{row_idx + 1}.png")}
        </visual>"""
        links.append(f"""
      <link name="row_{row_idx + 1}_frame">
        <pose>0 {yc:.3f} 0 0 0 0</pose>
        <collision name="sign_post_east">
          <pose>{ROW_HALF_LEN + 0.12:.2f} 0 0.75 0 0 0</pose>
          <geometry><box><size>0.04 0.04 1.5</size></box></geometry>
        </collision>
        <collision name="sign_post_west">
          <pose>{-ROW_HALF_LEN - 0.12:.2f} 0 0.75 0 0 0</pose>
          <geometry><box><size>0.04 0.04 1.5</size></box></geometry>
        </collision>
        <visual name="frame">
          <geometry><mesh><uri>model://greenhouse_tomato_rows/meshes/row_extras.obj</uri></mesh></geometry>
          {tex_material(pal)}
        </visual>{sign_vis}
      </link>""")

    with open(os.path.join(d, "model.sdf"), "w") as fh:
        fh.write(f"""<?xml version="1.0"?>
<!-- Generated by generate_greenhouse.py -->
<sdf version="1.9">
  <model name="greenhouse_tomato_rows">
    <static>true</static>{''.join(links)}
  </model>
</sdf>
""")
    model_config(d, "greenhouse_tomato_rows", "Double rows of high wire tomato plants on hanging gutters")
    return anchors_out


