class Mesh:
    def __init__(self):
        self.v = []
        self.n = []
        self.t = []
        self.f = []

    def add(self, verts, normals, uvs, faces):
        base = len(self.v)
        self.v.extend(verts)
        self.n.extend(normals)
        self.t.extend(uvs)
        self.f.extend([(a + base, b + base, c + base) for a, b, c in faces])

    def extend(self, other):
        self.add(other.v, other.n, other.t, other.f)

    def write(self, path):
        with open(path, "w") as fh:
            fh.write("# generated by generate_greenhouse.py\n")
            for x, y, z in self.v:
                fh.write(f"v {x:.4f} {y:.4f} {z:.4f}\n")
            for u, w in self.t:
                fh.write(f"vt {u:.4f} {w:.4f}\n")
            for x, y, z in self.n:
                fh.write(f"vn {x:.3f} {y:.3f} {z:.3f}\n")
            for a, b, c in self.f:
                a, b, c = a + 1, b + 1, c + 1
                fh.write(f"f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}\n")


def unit(v):
    v = np.asarray(v, dtype=float)
    n = np.linalg.norm(v)
    return v / n if n > 1e-12 else v


def box(mesh, center, size, color=None, yaw=0.0, tex_scale=None):
    """Axis box, palette color or world scaled UVs when tex_scale is given."""
    cx, cy, cz = center
    sx, sy, sz = (s / 2 for s in size)
    c, s = math.cos(yaw), math.sin(yaw)

    def tr(p):
        x, y, z = p
        return (cx + c * x - s * y, cy + s * x + c * y, cz + z)

    def rot(nv):
        x, y, z = nv
        return (c * x - s * y, s * x + c * y, z)

    faces = [
        ((1, 0, 0), [(sx, -sy, -sz), (sx, sy, -sz), (sx, sy, sz), (sx, -sy, sz)], (1, 2)),
        ((-1, 0, 0), [(-sx, sy, -sz), (-sx, -sy, -sz), (-sx, -sy, sz), (-sx, sy, sz)], (1, 2)),
        ((0, 1, 0), [(sx, sy, -sz), (-sx, sy, -sz), (-sx, sy, sz), (sx, sy, sz)], (0, 2)),
        ((0, -1, 0), [(-sx, -sy, -sz), (sx, -sy, -sz), (sx, -sy, sz), (-sx, -sy, sz)], (0, 2)),
        ((0, 0, 1), [(-sx, -sy, sz), (sx, -sy, sz), (sx, sy, sz), (-sx, sy, sz)], (0, 1)),
        ((0, 0, -1), [(-sx, sy, -sz), (sx, sy, -sz), (sx, -sy, -sz), (-sx, -sy, -sz)], (0, 1)),
    ]
    for nv, quad, axes in faces:
        verts = [tr(p) for p in quad]
        norms = [rot(nv)] * 4
        if tex_scale is None:
            uvs = [cell_uv(color)] * 4
        else:
            # Long axis of the face runs along u so wood grain follows the board
            a0, a1 = axes
            if size[a1] > size[a0]:
                a0, a1 = a1, a0
            off = (center[0] * 1.7 + center[1] * 2.3 + center[2] * 3.1) % 1.0
            uvs = [(p[a0] / tex_scale + off, p[a1] / tex_scale + off * 0.5) for p in quad]
        mesh.add(verts, norms, uvs, [(0, 1, 2), (0, 2, 3)])


def tube(mesh, pts, radii, color, sides=5, cap=False):
    pts = [np.asarray(p, dtype=float) for p in pts]
    n = len(pts)
    tangents = []
    for i in range(n):
        a = pts[max(i - 1, 0)]
        b = pts[min(i + 1, n - 1)]
        tangents.append(unit(b - a))
    ref = np.array([0.0, 0.0, 1.0])
    if abs(np.dot(ref, tangents[0])) > 0.9:
        ref = np.array([1.0, 0.0, 0.0])
    normal = unit(np.cross(tangents[0], ref))
    verts, norms, uvs, faces = [], [], [], []
    for i in range(n):
        t = tangents[i]
        normal = unit(normal - np.dot(normal, t) * t)
        binormal = np.cross(t, normal)
        for k in range(sides):
            a = 2 * math.pi * k / sides
            d = math.cos(a) * normal + math.sin(a) * binormal
            verts.append(tuple(pts[i] + radii[i] * d))
            norms.append(tuple(d))
            uvs.append(cell_uv(color))
    for i in range(n - 1):
        for k in range(sides):
            a = i * sides + k
            b = i * sides + (k + 1) % sides
            c2 = (i + 1) * sides + (k + 1) % sides
            d2 = (i + 1) * sides + k
            faces += [(a, b, c2), (a, c2, d2)]
    if cap:
        top = len(verts)
        verts.append(tuple(pts[-1]))
        norms.append(tuple(tangents[-1]))
        uvs.append(cell_uv(color))
        for k in range(sides):
            faces.append(((n - 1) * sides + k, (n - 1) * sides + (k + 1) % sides, top))
    mesh.add(verts, norms, uvs, faces)


def quad_ds(mesh, p0, p1, p2, p3, color):
    """Double sided quad."""
    p = [np.asarray(x, dtype=float) for x in (p0, p1, p2, p3)]
    nv = unit(np.cross(p[1] - p[0], p[3] - p[0]))
    uv = [cell_uv(color)] * 4
    mesh.add([tuple(x) for x in p], [tuple(nv)] * 4, uv, [(0, 1, 2), (0, 2, 3)])
    mesh.add([tuple(x) for x in p], [tuple(-nv)] * 4, uv, [(0, 2, 1), (0, 3, 2)])


def leaflet(mesh, origin, direction, side, length, width, color):
    """Pointed oval leaflet folded along the midrib, both faces."""
    d = unit(direction)
    s = unit(side - np.dot(side, d) * d)
    up = unit(np.cross(d, s))
    if up[2] < 0:
        up = -up
        s = -s
    stations = 6
    mid, left, right = [], [], []
    for i in range(stations):
        t = i / (stations - 1)
        hw = width * 0.5 * (math.sin(math.pi * t) ** 0.75) * (1.0 - 0.2 * t)
        # The leaflet curls down towards the tip
        p = origin + d * length * t - up * 0.25 * length * t * t
        mid.append(p)
        fold = up * (-0.18 * hw)
        left.append(p + s * hw + fold)
        right.append(p - s * hw + fold)
    verts = []
    for i in range(stations):
        verts.append(mid[i])
    for i in range(1, stations - 1):
        verts.append(left[i])
    for i in range(1, stations - 1):
        verts.append(right[i])

    def L(i):
        return stations + (i - 1)

    def R(i):
        return stations + (stations - 2) + (i - 1)

    faces = []
    for i in range(stations - 1):
        if i == 0:
            faces += [(0, L(1), 1), (0, 1, R(1))]
        elif i == stations - 2:
            faces += [(i, L(i), i + 1), (i, i + 1, R(i))]
        else:
            faces += [(i, L(i), L(i + 1)), (i, L(i + 1), i + 1),
                      (i, i + 1, R(i + 1)), (i, R(i + 1), R(i))]
    # Orient so the upper face points up
    a, b, c = faces[0]
    nrm = np.cross(verts[b] - verts[a], verts[c] - verts[a])
    if np.dot(nrm, up) < 0:
        faces = [(x, z, y) for x, y, z in faces]
    uv = [cell_uv(color)] * len(verts)
    vt = [tuple(v) for v in verts]
    mesh.add(vt, [tuple(up)] * len(vt), uv, faces)
    mesh.add(vt, [tuple(-up)] * len(vt), uv, [(x, z, y) for x, y, z in faces])


def compound_leaf(mesh, origin, yaw, length, color, droop=1.0):
    pts = []
    p = np.asarray(origin, dtype=float)
    pitch0 = math.radians(28)
    steps = 10
    for i in range(steps + 1):
        t = i / steps
        pitch = pitch0 - math.radians(75) * droop * t ** 1.3
        d = np.array([math.cos(pitch) * math.cos(yaw), math.cos(pitch) * math.sin(yaw), math.sin(pitch)])
        pts.append(p.copy())
        p = p + d * length / steps
    tube(mesh, pts, [0.0035 * (1 - 0.6 * i / steps) for i in range(steps + 1)], 0, sides=4)
    for frac, size in ((0.22, 0.08), (0.42, 0.12), (0.62, 0.14), (0.82, 0.13)):
        idx = int(frac * steps)
        base = pts[idx]
        tang = unit(pts[idx + 1] - pts[idx])
        horiz = unit(np.cross(tang, [0, 0, 1]))
        for sgn in (1, -1):
            jitter = rng.normal(0, 0.12)
            direction = unit(tang * 0.55 + sgn * horiz * 0.85 + np.array([0, 0, -0.15 + jitter]))
            ln = size * rng.uniform(0.85, 1.15)
            leaflet(mesh, base, direction, sgn * tang, ln, ln * 0.52, color)
    tip_dir = unit(pts[-1] - pts[-2])
    leaflet(mesh, pts[-1], tip_dir, unit(np.cross(tip_dir, [0, 0, 1])), 0.14, 0.075, color)


def plant_variant(seed):
    """One tomato plant in its local frame, base on the slab, trusses towards +x."""
    global rng
    rng = np.random.default_rng(seed)
    mesh = Mesh()
    height = 1.45 + rng.normal(0, 0.05)
    wire_local = WIRE_Z - SLAB_TOP
    # Main stem with a gentle wander
    pts = []
    off = np.zeros(2)
    nseg = int(height / 0.1)
    for i in range(nseg + 1):
        z = height * i / nseg
        off += rng.normal(0, 0.006, 2)
        off *= 0.92
        pts.append(np.array([off[0], off[1], z]))
    radii = [0.011 - 0.005 * (i / nseg) for i in range(nseg + 1)]
    tube(mesh, pts, radii, 0, sides=6, cap=True)

    def stem_at(z):
        i = min(int(z / height * nseg), nseg - 1)
        t = z / height * nseg - i
        return pts[i] * (1 - t) + pts[i + 1] * t

    # Twine from the growing tip to the high wire
    top = pts[-1]
    w = 0.002
    quad_ds(mesh, top + [-w, 0, 0], top + [w, 0, 0], [w, 0, wire_local], [-w, 0, wire_local], 7)
    quad_ds(mesh, top + [0, -w, 0], top + [0, w, 0], [0, w, wire_local], [0, -w, wire_local], 7)

    # Trusses in the harvest zone below the canopy, older ones lower
    trusses = []
    for k, zt in enumerate((0.42, 0.60, 0.78, 0.96, 1.14)):
        z = zt + rng.normal(0, 0.02)
        root = stem_at(z)
        yaw = rng.normal(0, 0.45)
        # The peduncle leaves the stem towards the aisle and the rachis then runs along the row
        # so every fruit faces the aisle and none hides behind another
        d = np.array([math.cos(yaw * 0.3), math.sin(yaw * 0.3), 0.0])
        along = np.array([0.0, 1.0, 0.0])
        ped = [root, root + d * 0.05 + [0, 0, 0.02], root + d * 0.10 + [0, 0, 0.0]]
        rachis = [ped[-1]]
        anchors = []
        pedicels = []
        n_fruit = int(rng.integers(3, 5))
        p = ped[-1].copy()
        for j in range(n_fruit):
            p = p + along * 0.10 + np.array([0, 0, -0.018])
            rachis.append(p.copy())
            side = 1 if j % 2 == 0 else -1
            tip = p + d * side * 0.012 + np.array([0, 0, -0.022])
            pedicels.append([p.copy(), tip])
            anchors.append(tip)
        trusses.append({"level": k, "anchors": anchors, "stalk": ped + rachis[1:], "pedicels": pedicels})

    # Leaves all along the stem, shorter on the truss side so the fruit stays visible
    yaw = rng.uniform(0, 2 * math.pi)
    z = 0.12
    while z < height - 0.08:
        yaw += math.radians(137.5) + rng.normal(0, 0.3)
        length = 0.34 + 0.10 * (1 - z / height) + rng.normal(0, 0.03)
        facing = math.cos(yaw)
        if facing > 0.25:
            length *= 0.45
        color = int(rng.choice([2, 3, 4, 5]))
        compound_leaf(mesh, stem_at(z), yaw, length, color, droop=rng.uniform(0.8, 1.2))
        z += 0.10 + rng.normal(0, 0.01)
    # Growing tip
    for k in range(3):
        compound_leaf(mesh, pts[-1], yaw + k * 2.1, 0.12, 5, droop=0.5)
    return mesh, trusses


def line_mesh():
    """Gutter, substrate slabs, heating pipes, drip line and end posts of one plant line."""
    m = Mesh()
    L = 2 * ROW_HALF_LEN
    # Hanging gutter and its stands
    box(m, (0, 0, 0.33), (L, 0.26, 0.06), 9)
    box(m, (0, 0.125, 0.355), (L, 0.01, 0.05), 9)
    box(m, (0, -0.125, 0.355), (L, 0.01, 0.05), 9)
    for x in np.arange(-ROW_HALF_LEN + 0.25, ROW_HALF_LEN, 1.25):
        box(m, (x, 0, 0.15), (0.04, 0.04, 0.30), 18)
        box(m, (x, 0, 0.29), (0.04, 0.30, 0.02), 18)
        box(m, (x, 0, 0.005), (0.14, 0.14, 0.01), 18)
    # Substrate slabs with small gaps
    for i in range(10):
        x0 = -ROW_HALF_LEN + i * 1.0 + 0.5
        box(m, (x0, 0, 0.40), (0.96, 0.18, 0.08), 8)
    # Drip line on the slabs
    tube(m, [(-ROW_HALF_LEN, 0.07, 0.447), (ROW_HALF_LEN, 0.07, 0.447)], [0.006, 0.006], 10, sides=4)
    # Heating pipes under the gutter
    for y in (-0.09, 0.09):
        tube(m, [(-ROW_HALF_LEN - 0.1, y, 0.12), (ROW_HALF_LEN + 0.1, y, 0.12)], [0.025, 0.025], 11, sides=8)
    for x in (-ROW_HALF_LEN - 0.12, ROW_HALF_LEN + 0.12):
        tube(m, [(x, -0.09, 0.12), (x, 0.09, 0.12)], [0.026, 0.026], 11, sides=8)
    # End posts and the high wire
    for x in (-ROW_HALF_LEN - 0.12, ROW_HALF_LEN + 0.12):
        box(m, (x, 0, (WIRE_Z + 0.08) / 2), (0.05, 0.05, WIRE_Z + 0.08), 18)
    tube(m, [(-ROW_HALF_LEN - 0.12, 0, WIRE_Z), (ROW_HALF_LEN + 0.12, 0, WIRE_Z)], [0.003, 0.003], 18, sides=4)
    return m


def row_extras_mesh():
    """Cross beams between the two lines of a double row, sticky traps, sign posts."""
    m = Mesh()
    for x in (-ROW_HALF_LEN - 0.12, ROW_HALF_LEN + 0.12):
        box(m, (x, 0, WIRE_Z + 0.06), (0.05, 2 * LINE_OFFSET + 0.05, 0.04), 18)
        box(m, (x, 0, 0.75), (0.04, 0.04, 1.5), 18)
    for x in (-3.3, 0.0, 3.3):
        for y in (-LINE_OFFSET, LINE_OFFSET):
            yy = y + (0.05 if y > 0 else -0.05)
            quad_ds(m, (x - 0.12, yy, 1.95), (x + 0.12, yy, 1.95), (x + 0.12, yy, 2.10), (x - 0.12, yy, 2.10), 12)
            quad_ds(m, (x - 0.002, yy, 2.10), (x + 0.002, yy, 2.10), (x + 0.002, y, WIRE_Z), (x - 0.002, y, WIRE_Z), 7)
    return m


